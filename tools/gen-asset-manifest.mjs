#!/usr/bin/env node
/**
 * Regenerates `src/loading/assetManifest.ts` — every file under `public/`
 * that the Shacks boot screen warms before the game is shown.
 *
 * Wired to the `predev` / `prebuild` npm hooks, so the list cannot drift from
 * what the game actually ships. Committed as well, so a bare `vite` still
 * type-checks.
 */
import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = join(ROOT, "public");
const OUT_FILE = join(ROOT, "src", "loading", "assetManifest.ts");

/** Top-level folders that never reach a player: design reference shots, and
 * the boot logo itself (the screen draws it, so it cannot queue behind 200
 * sprites). */
const SKIP_TOP_LEVEL = new Set(["reference", "docs", "loading-screen"]);
const KEEP = /\.(png|jpe?g|gif|webp|avif|svg|mp3|wav|ogg|m4a|woff2?|ttf|otf)$/i;

function walk(dir, out = []) {
  const entries = readdirSync(dir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    if (entry.name.startsWith(".")) continue;
    const full = join(dir, entry.name);
    const rel = relative(PUBLIC_DIR, full).split(sep).join("/");
    if (SKIP_TOP_LEVEL.has(rel.split("/")[0])) continue;
    if (entry.isDirectory()) walk(full, out);
    else if (KEEP.test(entry.name)) out.push(rel);
  }
  return out;
}

const files = existsSync(PUBLIC_DIR) ? walk(PUBLIC_DIR) : [];

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(
  OUT_FILE,
  `// AUTO-GENERATED by tools/gen-asset-manifest.mjs — do not edit by hand.\n` +
    `// Every shipped file under public/, warmed by the Shacks boot screen.\n` +
    `// ${files.length} file${files.length === 1 ? "" : "s"}.\n` +
    `export const ASSET_MANIFEST: readonly string[] = [\n` +
    files.map((f) => `  ${JSON.stringify(f)},\n`).join("") +
    `];\n`,
);

console.log(`asset manifest: ${files.length} files -> ${relative(ROOT, OUT_FILE)}`);
